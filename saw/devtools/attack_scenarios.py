def at(hour, minute=0, second=0, day=0):
    return DAY + timedelta(days=day, hours=hour, minutes=minute, seconds=second)


class Corpus:
    def __init__(self, seed: str):
        self.rng = random.Random(seed)
        self.seed = seed
        self.fw: list[list] = []
        self.ndr: list[list] = []

    def eport(self):
        return self.rng.randint(49152, 65000)

    def fw_row(self, t, src, dst, dport, *, action="허용", proto="TCP", flags="SYN,ACK,FIN",
               dur=1, sent=600, recv=1500, sport=None):
        sp = max(1, sent // 700) if sent else 0
        rp = max(1, recv // 1200) if recv else 0
        self.fw.append([t, GROUP, FW_DEVICE, action, src, sport or self.eport(), dst, dport, proto,
                        flags if proto == "TCP" else "", dur, sent, recv, sp + rp, sp, rp])

    def denied(self, t, src, dst, dport, proto="TCP"):
        self.fw_row(t, src, dst, dport, action="차단", proto=proto, flags="SYN", dur=0, sent=60, recv=0)

    def http(self, t, src, request, status, *, ua=BROWSER, sent=520, recv=2400, host=HOST, dst=WEB,
             port=443, label="", action="탐지"):
        n = len(self.ndr)
        self.ndr.append([t, "HTTP", GROUP, NDR_DEVICE, action, src, self.eport(), _country(src), dst, port,
                         "TCP", f"SYN-{self.seed}-{n:05d}", sent, recv, request, host, str(status), ua, label])

    def session(self, t, src, dst, dport, *, sent=600, recv=1500, proto="TCP", label="", kind="세션"):
        n = len(self.ndr)
        self.ndr.append([t, kind, GROUP, NDR_DEVICE, "탐지", src, self.eport(), _country(src), dst, dport, proto,
                         f"SYN-{self.seed}-{n:05d}", sent, recv, "", "", "", "", label])

    # ---- shared realistic background so behavioural detectors have a baseline ----
    def normal_web(self, count=90, start=9, end=18, dst=WEB, host=HOST):
        pages = ["/", "/main", "/notice/list", "/notice/view?id={n}", "/product/list?page={p}",
                 "/product/view?id={n}", "/static/app.js", "/static/style.css", "/images/logo.png",
                 "/api/me", "/api/notice?page={p}", "/faq", "/contact", "/login", "/mypage"]
        for _ in range(count):
            src = self.rng.choice(EMPLOYEES + CUSTOMERS)
            sec = self.rng.randint(start * 3600, end * 3600 - 1)
            path = self.rng.choice(pages).format(n=self.rng.randint(1, 400), p=self.rng.randint(1, 9))
            self.http(DAY + timedelta(seconds=sec), src, f"GET {path} HTTP/1.1",
                      self.rng.choice((200, 200, 200, 200, 304)), ua=self.rng.choice((BROWSER, BROWSER, MOBILE)),
                      recv=self.rng.randint(800, 40000), dst=dst, host=host)

    def normal_fw(self, count=70, start=9, end=18):
        for _ in range(count):
            src = self.rng.choice(EMPLOYEES)
            t = DAY + timedelta(seconds=self.rng.randint(start * 3600, end * 3600 - 1))
            r = self.rng.random()
            if r < 0.45:
                self.fw_row(t, src, self.rng.choice(SAAS), 443, dur=self.rng.randint(1, 120),
                            sent=self.rng.randint(800, 9000), recv=self.rng.randint(4000, 400000))
            elif r < 0.7:
                self.fw_row(t, src, DNS, 53, proto="UDP", dur=0, sent=80, recv=160)
            elif r < 0.9:
                self.fw_row(t, src, WEB, 443, dur=self.rng.randint(1, 60),
                            sent=self.rng.randint(600, 5000), recv=self.rng.randint(3000, 90000))
            else:
                self.fw_row(t, src, MAIL, 25, dur=2, sent=self.rng.randint(2000, 30000), recv=900)

    def to_csv(self, kind):
        rows = sorted(self.fw if kind == "fw" else self.ndr, key=lambda r: r[0])
        stream = io.StringIO(newline="")
        writer = csv.writer(stream, lineterminator="\r\n")
        writer.writerow(FW_COLUMNS if kind == "fw" else NDR_COLUMNS)
        for row in rows:
            row = list(row)
            row[0] = row[0].strftime("%Y-%m-%d %H:%M:%S")
            writer.writerow(row)
        return stream.getvalue().encode("cp949")


def _country(ip: str) -> str:
    if ip.startswith(("10.", "192.0.2.")):
        return "KR"
    if ip.startswith("203.0.113.") and int(ip.rsplit(".", 1)[1]) < 40:
        return "KR"
    return {EXT_A: "NL", EXT_B: "US", EXT_C: "SG", C2: "RU", DROP: "DE", POOL: "CN"}.get(ip, "DE")


@dataclass(frozen=True)
class Scenario:
    id: str
    title: str
    stage: str
    technique: tuple[str, ...]
    devices: tuple[str, ...]
    kind: str  # "attack" | "benign_control"
    summary: str
    expected_signal: str
    build: object = field(repr=False, compare=False)


REGISTRY: list[Scenario] = []


def scenario(id, title, stage, technique, devices, kind, summary, expected_signal):
    def wrap(fn):
        REGISTRY.append(Scenario(id, title, stage, tuple(technique), tuple(devices), kind, summary, expected_signal, fn))
        return fn
    return wrap


def enc(value: str) -> str:
    # Percent-encode spaces so the request line stays a single printable token.
    return value.replace(" ", "%20")


def _flood(c, src, paths, start, status=404, ua=BROWSER, recv=300, per=2):
    for i, path in enumerate(paths):
        c.http(start + timedelta(seconds=i * per), src, f"GET {enc(path)} HTTP/1.1",
               status(i) if callable(status) else status, ua=ua, recv=recv)



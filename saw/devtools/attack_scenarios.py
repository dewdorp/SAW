def _inject(c, src, endpoint, markers, start, status):
    for i, m in enumerate(markers):
        st = status(i) if callable(status) else status
        c.http(start + timedelta(seconds=i * 5), src, f"GET {enc(endpoint + m)} HTTP/1.1", st,
               ua=SCANNERS["sqlmap"] if "sql" in endpoint else PYREQ, recv=6000 if st == 200 else 2400)



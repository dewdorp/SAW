"""Deterministic synthetic FW/NDR attack-scenario corpus for analysis and later training.

Design rules (do not relax):
  * No source bank record is copied. Every address uses documentation/private ranges
    (192.0.2/24, 198.51.100/24, 203.0.113/24, 10.20/16) and *.example.test hosts.
  * No weaponizable content. The corpus never contains working reverse shells,
    download-and-execute chains, live RCE gadget strings, deserialization payloads,
    or webshell bodies. "Dangerous" stages (command execution, C2, exfiltration,
    persistence) are represented by their *behavioural* footprint (status codes,
    byte volumes, timing, odd-port egress) plus a clearly defanged marker token.
    A guardrail test asserts the generated bytes contain none of a denylist.
  * Textbook, non-functional indicators (scanner User-Agents, suspicious paths,
    classic ' OR '1'='1 style markers) are used only where a human/detector needs
    to recognise the request *shape*; they do nothing in a log field.
  * Every file and row-group carries a label (scenario id, MITRE technique, kill-chain
    stage, benign/attack) in manifest.jsonl so the corpus is usable as training data.

The labels are the ground truth for training; the log rows are the features.
"""

DENYLIST = ("/dev/tcp", "bash -i", "/bin/sh", "powershell -e", "-enc ", "wget ", "curl http", "| sh", ";sh ",
            "jndi:", "${", "<?php", "eval(", "system(", "msfvenom", "meterpreter", "/etc/shadow", "nc -e")


def generate(output_dir: Path) -> dict:
    output_dir = Path(output_dir)
    output_dir.mkdir(parents=True, exist_ok=False)
    ids = [s.id for s in REGISTRY]
    if len(ids) != len(set(ids)):
        raise ValueError("duplicate scenario id")
    catalog, manifest = [], []
    files_dir = output_dir / "files"
    files_dir.mkdir()
    for s in REGISTRY:
        corpus = Corpus(s.id)
        s.build(corpus)
        outputs = {}
        for kind in ("fw", "ndr"):
            if kind in s.devices:
                data = corpus.to_csv(kind)
                low = data.decode("cp949").lower()
                for bad in DENYLIST:
                    if bad in low:
                        raise ValueError(f"scenario {s.id}: generated {kind} contains forbidden token {bad!r}")
                name = f"{s.id}.{kind}.csv"
                (files_dir / name).write_bytes(data)
                outputs[kind] = {"file": f"files/{name}", "bytes": len(data),
                                 "rows": len(corpus.fw if kind == "fw" else corpus.ndr)}
        if not outputs:
            raise ValueError(f"scenario {s.id}: produced no files")
        record = {"schema": SCHEMA, "id": s.id, "title": s.title, "kind": s.kind, "stage": s.stage,
                  "technique": list(s.technique), "devices": list(s.devices), "summary": s.summary,
                  "expected_signal": s.expected_signal, "outputs": outputs,
                  "synthetic": True, "contains_live_payload": False}
        manifest.append(record)
        catalog.append({k: record[k] for k in ("id", "title", "kind", "stage", "technique", "summary", "expected_signal")})
    with (output_dir / "manifest.jsonl").open("w", encoding="utf-8", newline="\n") as handle:
        for record in manifest:
            handle.write(json.dumps(record, ensure_ascii=False) + "\n")
    summary = {"schema": SCHEMA, "scenarios": len(manifest),
               "attack": sum(r["kind"] == "attack" for r in manifest),
               "benign_control": sum(r["kind"] == "benign_control" for r in manifest),
               "stages": sorted({r["stage"] for r in manifest}),
               "techniques": sorted({t for r in manifest for t in r["technique"]}),
               "files": sum(len(r["outputs"]) for r in manifest)}
    with (output_dir / "catalog.json").open("w", encoding="utf-8", newline="\n") as handle:
        json.dump({**summary, "catalog": catalog}, handle, ensure_ascii=False, indent=2)
        handle.write("\n")
    return summary


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("output", type=Path)
    args = parser.parse_args()
    print(json.dumps(generate(args.output), ensure_ascii=False))


if __name__ == "__main__":
    main()
